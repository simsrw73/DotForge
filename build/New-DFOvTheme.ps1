<#
.SYNOPSIS
    Writes ov's catppuccin theme configs: Tools/ov/catppuccin-<flavor>/config.yaml.
.DESCRIPTION
    Author-time only (the module never loads it). Takes ov's own default config
    (ov --generate-config=default), so every other setting keeps ov's defaults, and
    replaces each Foreground/Background color by its catppuccin counterpart. A color
    with no mapping stops the script, so a new ov release can't ship a stray color.
    Rerun after upgrading ov; tests/ov.Tests.ps1 checks the output.
.PARAMETER OutputRoot
    The folder that receives catppuccin-<flavor>/config.yaml. Default: Tools/ov.
.EXAMPLE
    pwsh -NoProfile -File build/New-DFOvTheme.ps1

    Regenerates the four flavors from the installed ov.
#>
[CmdletBinding()]
param([string]$OutputRoot = (Join-Path $PSScriptRoot '..' 'Tools' 'ov'))

$palettes = @{
    mocha     = @{ red = '#f38ba8'; maroon = '#eba0ac'; peach = '#fab387'; yellow = '#f9e2af'; green = '#a6e3a1'; sky = '#89dceb'; blue = '#89b4fa'; pink = '#f5c2e7'; text = '#cdd6f4'; overlay0 = '#6c7086'; surface2 = '#585b70'; surface1 = '#45475a'; surface0 = '#313244' }
    macchiato = @{ red = '#ed8796'; maroon = '#ee99a0'; peach = '#f5a97f'; yellow = '#eed49f'; green = '#a6da95'; sky = '#91d7e3'; blue = '#8aadf4'; pink = '#f5bde6'; text = '#cad3f5'; overlay0 = '#6e738d'; surface2 = '#5b6078'; surface1 = '#494d64'; surface0 = '#363a4f' }
    frappe    = @{ red = '#e78284'; maroon = '#ea999c'; peach = '#ef9f76'; yellow = '#e5c890'; green = '#a6d189'; sky = '#99d1db'; blue = '#8caaee'; pink = '#f4b8e4'; text = '#c6d0f5'; overlay0 = '#737994'; surface2 = '#626880'; surface1 = '#51576d'; surface0 = '#414559' }
    latte     = @{ red = '#d20f39'; maroon = '#e64553'; peach = '#fe640b'; yellow = '#df8e1d'; green = '#40a02b'; sky = '#04a5e5'; blue = '#1e66f5'; pink = '#ea76cb'; text = '#4c4f69'; overlay0 = '#9ca0b0'; surface2 = '#acb0be'; surface1 = '#bcc0cc'; surface0 = '#ccd0da' }
}
$foreground = @{ blue = 'blue'; lime = 'green'; yellowgreen = 'green'; aqua = 'sky'; red = 'red'; yellow = 'yellow'; fuchsia = 'pink'; crimson = 'maroon'; lightsalmon = 'peach'; gray = 'overlay0'; white = 'text'; '#CCCCCC' = 'text' }
$background = @{ '#333333' = 'surface0'; gray = 'surface1'; blue = 'surface1'; darkgoldenrod = 'surface2'; slateblue = 'surface2'; '#c0c0c0' = 'overlay0' }

$default = & ov --generate-config=default
if ($LASTEXITCODE) { throw 'ov --generate-config=default failed; is ov installed?' }
$version = (& ov --version | Select-Object -First 1)

foreach ($flavor in $palettes.Keys) {
    $palette = $palettes[$flavor]
    $lines = foreach ($line in $default) {
        if ($line -match '^(?<lead>\s*-?\s*)(?<key>Foreground|Background): "(?<color>[^"]+)"(?<rest>.*)$') {
            $map = if ($Matches.key -eq 'Foreground') { $foreground } else { $background }
            $name = $map[$Matches.color]
            if (-not $name) { throw "No catppuccin mapping for $($Matches.key) '$($Matches.color)'" }
            "$($Matches.lead)$($Matches.key): `"$($palette[$name])`"$($Matches.rest)"
        } else { $line }
    }
    $header = @(
        "# ov theme: catppuccin $flavor, generated by build/New-DFOvTheme.ps1 from"
        "# '$version' --generate-config=default. Colors: catppuccin palette (MIT, see ../LICENSE-catppuccin)."
        '# DotForge passes this file with --config only when you have no ov config of your own.'
    )
    $folder = Join-Path $OutputRoot "catppuccin-$flavor"
    New-Item -ItemType Directory -Force -Path $folder | Out-Null
    Set-Content -Path (Join-Path $folder 'config.yaml') -Value (@($header) + @($lines))
}
